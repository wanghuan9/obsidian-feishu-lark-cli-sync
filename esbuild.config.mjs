import builtins from "builtin-modules";
import esbuild from "esbuild";
import process from "process";

const banner =
`/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
*/
`;

const prod = process.argv[2] === "production";

const context = await esbuild.context({
	banner: {
		js: banner
	},
	bundle: true,
	entryPoints: ["main.ts"],
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		...builtins
	],
	format: "cjs",
	logLevel: "info",
	minify: prod,
	outfile: "main.js",
	sourcemap: prod ? false : "inline",
	target: "es2021",
	treeShaking: true
});

if (prod) {
	await context.rebuild();
	await esbuild.build({
		bundle: true,
		entryPoints: ["lark-sync-core.ts"],
		format: "esm",
		logLevel: "info",
		minify: prod,
		outfile: "lark-sync-core.mjs",
		platform: "node",
		target: "node20",
		treeShaking: true
	});
	process.exit(0);
}

await context.watch();
